#!/usr/bin/env node
// Renders the app's privacy policy into privacy/index.html, so the site and the app show the same
// text from one source: plex-client-tvos/Mutoscope/Legal/PrivacyPolicy.md.
//   node tools/render-privacy.js [path/to/PrivacyPolicy.md]
// Without a path it reads the app repo beside this one (~/Desktop/plex-client-tvos).
//
// It understands the Markdown the policy uses, and stops with an error on anything else rather
// than publishing it garbled: "# " title (once, first), "## " headings, paragraphs, "- " lists
// and **bold**. "mutoscope.app" in the text links to the support page.
'use strict';

const fs = require('fs');
const path = require('path');

const site = path.resolve(__dirname, '..');
const source = path.resolve(process.argv[2] ||
  path.join(site, '..', 'plex-client-tvos', 'Mutoscope', 'Legal', 'PrivacyPolicy.md'));
const output = path.join(site, 'privacy', 'index.html');

function fail(message) {
  console.error(`render-privacy: ${message}`);
  process.exit(1);
}

const escapeHTML = text => text
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Inline text: escaped, **bold**, and mutoscope.app linked to the support page.
function inline(text, where) {
  if (/`|\[[^\]]*\]\(|<[a-z/!]|(^|[^*])\*(?!\*)|_{2}/i.test(text.replace(/\*\*[^*]+\*\*/g, ''))) {
    fail(`${where}: unsupported Markdown (code, link, HTML or single-* emphasis): ${text}`);
  }
  if ((text.match(/\*\*/g) || []).length % 2) fail(`${where}: unmatched ** in: ${text}`);
  return escapeHTML(text)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(?<![@\w.\/])mutoscope\.app\b(?!\/)/g, '<a href="../support/">mutoscope.app</a>');
}

function render(markdown) {
  const lines = markdown.replace(/\r\n?/g, '\n').split('\n');
  const html = [];
  let title = null, paragraph = [], list = [];
  const flushParagraph = line => {
    if (paragraph.length) html.push(`<p>${inline(paragraph.join(' '), `line ${line}`)}</p>`);
    paragraph = [];
  };
  const flushList = line => {
    if (list.length) html.push('<ul>\n' + list.map(item => `  <li>${inline(item, `line ${line}`)}</li>`).join('\n') + '\n</ul>');
    list = [];
  };
  lines.forEach((raw, index) => {
    const n = index + 1;
    const line = raw.trimEnd();
    if (line === '') { flushParagraph(n); flushList(n); return; }
    if (/^#\s/.test(line)) {
      if (title !== null || html.length || paragraph.length) fail(`line ${n}: the "# " title must come first, once`);
      title = line.slice(2).trim();
      return;
    }
    if (/^##\s/.test(line)) {
      flushParagraph(n); flushList(n);
      html.push(`<h2>${inline(line.slice(3).trim(), `line ${n}`)}</h2>`);
      return;
    }
    if (/^- /.test(line)) {
      flushParagraph(n);
      list.push(line.slice(2).trim());
      return;
    }
    if (/^(#{3,}|\s*[*+]\s|\s*\d+[.)]\s|>|```|\||\s{2,}-)/.test(raw)) fail(`line ${n}: unsupported Markdown: ${raw}`);
    if (list.length) fail(`line ${n}: a list item runs onto a second line; keep each item on one line`);
    paragraph.push(line.trim());
  });
  flushParagraph(lines.length); flushList(lines.length);
  if (!title) fail('no "# " title');
  if (!html.length) fail('no content');
  return { title, body: html.join('\n') };
}

let markdown;
try {
  markdown = fs.readFileSync(source, 'utf8');
} catch (error) {
  fail(`can't read ${source}: ${error.message}`);
}
const { title, body } = render(markdown);
const indent = text => text.split('\n').map(l => (l ? '      ' + l : l)).join('\n');

const page = `<!doctype html>
<!-- Generated by tools/render-privacy.js from plex-client-tvos/Mutoscope/Legal/PrivacyPolicy.md.
     Don't edit this file: change the policy there and run the script again. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>${escapeHTML(title)} · Mutoscope</title>
  <meta name="description" content="Mutoscope's privacy policy.">
  <meta name="theme-color" content="#111214">
  <link rel="icon" href="../favicon.svg" type="image/svg+xml">
  <link rel="apple-touch-icon" href="../apple-touch-icon.png">
  <link rel="stylesheet" href="../assets/site.css">
</head>
<body class="document-page">
  <header class="site-header">
    <a class="brand" href="../"><img src="../assets/reel-still.svg" alt="" width="40" height="40">Mutoscope</a>
  </header>
  <main class="document">
    <article>
      <h1>${escapeHTML(title)}</h1>
${indent(body)}
    </article>
  </main>
  <footer class="site-footer">
    <a href="../privacy/" aria-current="page">Privacy</a>
    <a href="../support/">Support</a>
  </footer>
</body>
</html>
`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, page);
console.log(`wrote ${path.relative(site, output)} from ${source}`);
